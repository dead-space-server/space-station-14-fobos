    public BanTemplatesWindow()
    {
        RobustXamlLoader.Load(this);

        foreach (var (name, reason) in _templates)
        {
            var button = new Button
            {
                Text = name,
                Margin = new Thickness(4)
            };
            var capturedReason = reason;
            button.OnPressed += _ =>
            {
                OnTemplateSelected?.Invoke(capturedReason);
                Close();
            };
            TemplatesContainer.AddChild(button);
        }
    }
