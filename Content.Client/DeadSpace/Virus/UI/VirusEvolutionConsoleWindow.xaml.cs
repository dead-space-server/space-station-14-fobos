using System.Linq;
using Content.Shared.DeadSpace.Virus.Prototypes;
using Content.Shared.Virus;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client.DeadSpace.Virus.UI;

[GenerateTypedNameReferences]
public sealed partial class VirusEvolutionConsoleWindow : DefaultWindow
{
    [Dependency] private readonly IPrototypeManager _prototype = default!;
    private VirusEvolutionConsoleBoundUserInterfaceState? _lastUpdate;

    public VirusEvolutionConsoleWindow()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);
    }

    public void Populate(VirusEvolutionConsoleBoundUserInterfaceState state)
    {
        _lastUpdate = state;

        var data = state.Data;
        var selectedSymptom = AvailableSymptomsList.GetSelected();
        // Очки мутации
        MutationPointsLabel.Text = Loc.GetString("virus-evolution-mutation-points", ("points", state.MutationPoints));

        // Активные симптомы
        ActiveSymptomsList.Clear();
        foreach (var active in data.ActiveSymptom)
        {
            ActiveSymptomsList.AddItem(active.ToString());
        }

        // Доступные симптомы
        AvailableSymptomsList.Clear();
        foreach (var proto in IoCManager.Resolve<IPrototypeManager>().EnumeratePrototypes<VirusSymptomPrototype>())
        {
            if (!data.ActiveSymptom.Contains(proto.ID))
            {
                var price = proto.Price * Math.Max(1, data.ActiveSymptom.Count);
                AvailableSymptomsList.AddItem($"{proto.Name} ({price})");
            }
        }

        // Whitelist
        BodyWhitelistList.Clear();
        foreach (var body in data.BodyWhitelist)
        {
            BodyWhitelistList.AddItem(body.ToString());
        }

        // По выбранному симптому обновляем цену
        if (selectedSymptom.Any())
        {
            var selectedId = selectedSymptom.FirstOrDefault()?.Text;
            var proto = _prototype.Index<VirusSymptomPrototype>(AvailableSymptomsList[selectedId].Text);
            var cost = proto.Price * Math.Max(1, data.ActiveSymptom.Count);
            SymptomCostLabel.Text = Loc.GetString("virus-evolution-cost-label", ("cost", cost));
            BuySymptomButton.Disabled = state.MutationPoints < cost;
        }
        else
        {
            SymptomCostLabel.Text = "";
            BuySymptomButton.Disabled = true;
        }

        // По выбранному телу
        if (BodyWhitelistList.SelectedItem >= 0)
        {
            BuyBodyButton.Disabled = false;
        }
        else
        {
            BuyBodyButton.Disabled = true;
        }
    }

}
